// Reads design/tokens.json (Figma export, source of truth) and writes src/styles/tokens.css.
// Usage: node scripts/build-tokens.mjs [outFile]   (default: src/styles/tokens.css)
// Idempotent: the output depends only on tokens.json (no timestamps).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'design', 'tokens.json');
const out = path.resolve(process.argv[2] ?? path.join(root, 'src', 'styles', 'tokens.css'));

const tokens = JSON.parse(fs.readFileSync(src, 'utf8'));
const slug = (k) => k.replaceAll('/', '-');
const px = (v) => `${v}px`;

const DENSITY = {
  'density/row-height': '--row-height',
  'density/row-padding-x': '--row-padding-x',
  'density/row-padding-y': '--row-padding-y',
  'density/control-height': '--control-height',
};

function dimensionLines(set, { densityOnly = false } = {}) {
  const lines = [];
  for (const [k, v] of Object.entries(set)) {
    if (DENSITY[k]) lines.push(`  ${DENSITY[k]}: ${px(v)};`);
    else if (!densityOnly) lines.push(`  --${slug(k)}: ${px(v)};`);
  }
  return lines;
}

const lines = [];
lines.push('/* GENERATED by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */');
lines.push(`/* ${tokens.source} */`);
lines.push('');
lines.push(':root {');
lines.push(`  --font-family: "${tokens.fontFamily}", system-ui, sans-serif;`);
for (const [k, v] of Object.entries(tokens.color)) lines.push(`  --color-${slug(k)}: ${v};`);
lines.push(...dimensionLines(tokens.dimension.comfortable));
for (const [k, v] of Object.entries(tokens.effect)) lines.push(`  --shadow-${slug(k)}: ${v};`);
lines.push('}');
lines.push('');
lines.push('[data-density="compact"] {');
lines.push(...dimensionLines(tokens.dimension.compact, { densityOnly: true }));
lines.push('}');
lines.push('');
for (const [k, t] of Object.entries(tokens.text)) {
  lines.push(`.t-${k} {`);
  lines.push('  font-family: var(--font-family);');
  lines.push(`  font-weight: ${t.weight};`);
  lines.push(`  font-size: ${px(t.size)};`);
  lines.push(`  line-height: ${px(t.lineHeight)};`);
  if (t.tabular) lines.push('  font-variant-numeric: tabular-nums;');
  lines.push('}');
}
const css = lines.join('\n') + '\n';

fs.mkdirSync(path.dirname(out), { recursive: true });
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== css) fs.writeFileSync(out, css);
console.log(`tokens → ${path.relative(process.cwd(), out)}`);
